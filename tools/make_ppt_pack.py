def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    try:
        data = load_all()
    except MissingDataError as exc:
        print(str(exc), file=sys.stderr)
        return 2

    brightness: list[float] = []
    chosen: list[FrameTiming] = []
    relaxed = False
    if VIDEO.is_file():
        try:
            brightness, total = video_brightness(VIDEO, len(data.frames))
            chosen, relaxed = choose_frames(data.frames, brightness)
            print(f"video: {total} frames; brightness sampled for {len(brightness)} CSV rows")
        except OSError as exc:
            warn(str(exc))
    else:
        warn(f"{VIDEO.relative_to(ROOT)} is absent; side-by-side images will be placeholders")
    if not chosen:
        warn("no side-by-side frames met the selection rule; placeholders will be written")
        chosen = [data.frames[0], data.frames[min(1, len(data.frames) - 1)],
                  data.frames[min(2, len(data.frames) - 1)]]
        brightness = brightness or [0.0] * len(data.frames)
        relaxed = True

    cls_names = yolo_classes()
    build_01(data)
    build_02(data, chosen, brightness, relaxed, cls_names)
    build_03(data)
    build_04(data)
    build_05(data)
    build_06(data)
    build_07(data)
    build_08(data)
    build_09(data)
    build_10(data)
    build_11(data)
    write_index(data, chosen, relaxed)
    maybe_deck()

    print("\nPack summary (data-backed vs placeholder):")
    for stem in STEMS:
        print(f"  {stem}.png: {STATUS.get(stem, 'not built')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
