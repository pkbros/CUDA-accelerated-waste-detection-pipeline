    c.text(0.04, 0.842, f"classes: {class_text}", size=MINI, color=MUTED)
    c.value("classes", class_text, source="waste.yaml")

    if data.finetune:
        c.rect(0.04, 0.755, 0.92, 0.075, face="white", edge=TEAL, lw=1.6, rounded=True)
        c.text(0.06, 0.792, f"mAP50 ({data.finetune.map50_name}): {fmt(data.finetune.map50, 3)}",
               size=BODY, color=TEAL, weight="bold")
        c.value(data.finetune.map50_name, f"{data.finetune.map50:.6f}", source="finetune.csv")
        if data.finetune.map50_95 is not None:
            c.text(0.52, 0.792,
                   f"mAP50-95 ({data.finetune.map50_95_name}): {fmt(data.finetune.map50_95, 3)}",
                   size=BODY, color=TEAL, weight="bold")
            c.value(data.finetune.map50_95_name, f"{data.finetune.map50_95:.6f}", source="finetune.csv")
        status = "data-backed"
    else:
        c.rect(0.04, 0.755, 0.92, 0.075, face="white", edge=ORANGE, lw=1.6, rounded=True)
        c.text(0.06, 0.792, "NOT RUN: no fine-tune metrics", size=BODY,
               color=ORANGE_DARK, weight="bold")
        c.text(0.52, 0.792, "pretrained COCO, no mAP measured", size=BODY, color=MUTED)
        c.value("NOT RUN", None, source="finetune.csv", note="no fine-tune metrics")
        status = "partial: 6 val frames real, mAP NOT RUN"

    if not chosen:
        c.placeholder("data/waste/images/val has no readable images",
                      panel="val frames", source="waste.yaml", y=0.5)
        c.finish(footer_for(data, stem), "placeholder: val images missing")
        return

    for i, path in enumerate(chosen):
        col, row = i % 3, i // 3
        x0 = 0.035 + col * 0.32
        y0 = 0.425 - row * 0.31
        w, h = 0.30, 0.305
        boxes = val_boxes(path)
        c.text(x0 + 0.006, y0 + h - 0.004, path.stem[:26], size=MINI, color=MUTED)
        ax = c.fig.add_axes([x0, y0, w, h - 0.032], facecolor="white")
        ax.set_axis_off()
