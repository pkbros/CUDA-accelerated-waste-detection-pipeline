def build_01(data: PPTData) -> None:
    stem = "01_pipeline_stages"
    c = Canvas(stem, ["demo_frame_timings.csv", "device.json"])
    stats = per_frame_stats(data.frames)
    stages = (
        ("Frame decode", "baseline_decode_ms", "opt_decode_ms"),
        ("Preprocess", "baseline_preprocess_ms", "opt_preprocess_ms"),
        ("Inference", "baseline_infer_ms", "opt_infer_ms"),
        ("Postprocess / NMS", "baseline_post_ms", "opt_post_ms"),
    )
    c.text(0.04, 0.945, "Four stages: baseline vs optimized", size=TITLE, weight="bold")
    c.text(
        0.04, 0.882,
        f"mean per frame over {stats.n_frames} measured frames: "
        f"{fmt(stats.baseline_total_mean_ms)} ms baseline vs {fmt(stats.opt_total_mean_ms)} ms optimized",
        size=SUBTITLE, color=MUTED,
    )
    c.value("frames", stats.n_frames, unit="frames", source="demo_frame_timings.csv")
    c.value("mean baseline total", f"{stats.baseline_total_mean_ms:.6f}", unit="ms", source="demo_frame_timings.csv")
    c.value("mean optimized total", f"{stats.opt_total_mean_ms:.6f}", unit="ms", source="demo_frame_timings.csv")

    y, h = 0.47, 0.21
    xs = (0.035, 0.275, 0.515, 0.755)
    w = 0.205
    for i, (name, base_key, opt_key) in enumerate(stages):
        base_mean = float(sum(getattr(f, base_key) for f in data.frames) / stats.n_frames)
        opt_mean = float(sum(getattr(f, opt_key) for f in data.frames) / stats.n_frames)
        c.rect(xs[i], y, w, h, face="white", edge=INK, lw=2.0, rounded=True)
        c.text(xs[i] + w / 2, y + h * 0.60, name, size=VALUE, ha="center", weight="bold")
        c.text(xs[i] + w / 2, y + h * 0.27, "measured mean", size=MINI, ha="center", color=MUTED)
        c.text(xs[i] + 0.01, 0.345, f"baseline {fmt(base_mean)} ms",
               size=VALUE, color=ORANGE, weight="bold")
        c.text(xs[i] + 0.01, 0.285, f"optimized {fmt(opt_mean)} ms",
               size=VALUE, color=TEAL, weight="bold")
        if i < len(stages) - 1:
            c.arrow(xs[i] + w + 0.008, y + h / 2, xs[i + 1] - 0.008)
        c.value(f"{name} baseline", f"{base_mean:.6f}", unit="ms", panel=name,
                source="demo_frame_timings.csv", note="mean across all frames")
        c.value(f"{name} optimized", f"{opt_mean:.6f}", unit="ms", panel=name,
                source="demo_frame_timings.csv", note="mean across all frames")
    c.text(0.5, 0.19, "Read the four pairs as a pipeline: each pair is the same stage, measured twice.",
           size=BODY, ha="center", color=MUTED)
    c.finish(footer_for(data, stem), "data-backed")


