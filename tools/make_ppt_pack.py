def video_brightness(path: Path, n_positions: int) -> tuple[list[float], int]:
    """Mean grayscale brightness of the first ``n_positions`` video frames."""
    cap = cv2.VideoCapture(str(path))
    if not cap.isOpened():
        raise OSError(f"could not open {path}")
    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    values: list[float] = []
    for _ in range(min(n_positions, total if total > 0 else n_positions)):
        ok, bgr = cap.read()
        if not ok:
            break
        values.append(float(np.mean(cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY))))
    cap.release()
    return values, total


def video_frame(path: Path, index: int) -> np.ndarray | None:
    cap = cv2.VideoCapture(str(path))
    if not cap.isOpened():
        return None
    cap.set(cv2.CAP_PROP_POS_FRAMES, index)
    ok, bgr = cap.read()
    cap.release()
    if not ok:
        return None
    return cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)


def bright_val_images(images: list[Path], threshold: float = 40.0) -> list[Path]:
    """Keep val frames whose grayscale mean clears the visibility threshold.

    This is a selection filter only: no brightness number is printed on an
    image or written to its data CSV.
    """
    out: list[Path] = []
    for path in images:
        bgr = cv2.imread(str(path))
        if bgr is None:
            continue
        if float(np.mean(cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY))) > threshold:
            out.append(path)
    return out


def choose_frames(
    frames: list[FrameTiming], brightness: list[float]
) -> tuple[list[FrameTiming], bool]:
    """Pick 3 bright frames with >=3 detections, spread across the clip."""

    def candidates(min_det: int) -> list[FrameTiming]:
        return [
            f for f in frames
            if f.position < len(brightness)
            and brightness[f.position] > 40.0
            and f.baseline_detections >= min_det
        ]

    relaxed = False
    pool = candidates(3)
    if not pool:
        pool = candidates(1)
        relaxed = True
    if not pool:
        return [], relaxed

    n = len(frames)
    chosen: list[FrameTiming] = []
    for segment in range(3):
        lo, hi = segment * n // 3, (segment + 1) * n // 3
        in_seg = [f for f in pool if lo <= f.position < hi and f not in chosen]
        if not in_seg:
            in_seg = [f for f in pool if f not in chosen]
        if not in_seg:
            continue
        target = (lo + hi) / 2.0
        pick = max(
            in_seg,
            key=lambda f: (f.baseline_detections, brightness[f.position], -abs(f.position - target)),
        )
        chosen.append(pick)
    for f in sorted(pool, key=lambda f: -f.baseline_detections):
        if len(chosen) >= 3:
            break
        if f in chosen:
            continue
        if all(abs(f.position - c.position) >= 3 for c in chosen):
            chosen.append(f)
    chosen.sort(key=lambda f: f.position)
    return chosen[:3], relaxed


def draw_frame_panel(
    canvas: Canvas,
    ax: Any,
    rgb: np.ndarray,
    boxes: Iterable[Any],
    color: str,
    cls_names: dict[int, str],
    *,
    show_score: bool = True,
) -> None:
    """Contain-fit one frame and draw thin boxes with large class labels."""
    x0, y0, w, h = ax.get_position().bounds
    px_w, px_h = w * FIG_W, h * FIG_H
    ih, iw = rgb.shape[:2]
    scale = min(px_w / max(1, iw), px_h / max(1, ih))
    disp_w, disp_h = iw * scale, ih * scale
    dx, dy = (px_w - disp_w) / 2.0, (px_h - disp_h) / 2.0
    xlo, ylo = dx / FIG_W, dy / FIG_H
    xhi, yhi = (dx + disp_w) / FIG_W, (dy + disp_h) / FIG_H
    ax.imshow(rgb, extent=[xlo, xhi, ylo, yhi], aspect="auto", interpolation="bilinear")

    def sx(value: float) -> float:
        return xlo + max(0.0, min(iw, value)) * scale / FIG_W

    def sy(value: float) -> float:
        return yhi - max(0.0, min(ih, value)) * scale / FIG_H

    for box in boxes:
        x1, x2 = sorted((sx(box.x1), sx(box.x2)))
        top, bottom = sorted((sy(box.y1), sy(box.y2)))
        if x2 - x1 < 0.001 or bottom - top < 0.001:
            continue
        ax.add_patch(
            Rectangle((x1, bottom), x2 - x1, top - bottom, transform=ax.transData,
                      fill=False, edgecolor=color, linewidth=2.2)
        )
        name = cls_names.get(box.cls)
        base = name or f"cls {box.cls}"
        label = f"{base} {box.score:.2f}" if show_score else base
        ax.text(
            x1, top + 0.006, label, fontsize=BOX_LABEL, color="white",
            va="bottom", ha="left",
            bbox=dict(facecolor=color, edgecolor="none", pad=1.2),
        )


