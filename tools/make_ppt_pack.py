# 09 -- multi-feed
# --------------------------------------------------------------------------- #


def build_09(data: PPTData) -> None:
    stem = "09_multi_feed"
    c = Canvas(stem, ["batching.csv", "device.json"])
    feeds = multi_feed(data)
    present = sorted(feeds)
    worse: list[int] = []
    better: list[int] = []
    for feed in present:
        pair = feeds[feed]
        if "serial_batch" in pair and "pipelined_batch" in pair:
            serial = float(pair["serial_batch"].extra["fps_per_feed"])
            pipe = float(pair["pipelined_batch"].extra["fps_per_feed"])
            (worse if pipe < serial else better).append(feed)
            c.value(f"serial fps_per_feed {feed}", f"{serial:.6f}", unit="FPS",
                    source="batching.csv")
            c.value(f"pipelined fps_per_feed {feed}", f"{pipe:.6f}", unit="FPS",
                    source="batching.csv")
    verdict = (
        f"Pipelining got worse at {', '.join(str(f) for f in worse)} feeds"
        if worse else "Pipelining did not get worse at the measured feeds"
    )
    c.text(0.04, 0.95, f"Multi-feed: {verdict}", size=TITLE, weight="bold")
    pair4 = feeds.get(4, {})
    if "serial_batch" in pair4 and "pipelined_batch" in pair4:
        serial4 = float(pair4["serial_batch"].extra["fps_per_feed"])
        pipe4 = float(pair4["pipelined_batch"].extra["fps_per_feed"])
        detail = (f"FPS/feed from batching.csv extra | 4 feeds: serial {fmt(serial4, 1)} "
                  f"vs pipelined {fmt(pipe4, 1)} FPS/feed")
    else:
        detail = "FPS per feed from the extra field of batching.csv; absent rows read NOT RUN"
    c.text(0.04, 0.885, detail, size=SUBTITLE, color=MUTED)
    c.value("feeds measured", ",".join(str(f) for f in present), source="batching.csv")

    y0, y1 = 0.26, 0.74
    c.line(0.075, y0, 0.965, y0, color=INK, lw=2.0)
    c.text(0.045, y1, "FPS", size=MINI, ha="right")
    all_v = [
        float(r.extra["fps_per_feed"])
        for pair in feeds.values() for r in pair.values()
    ]
    ymax = max(all_v) * 1.20 if all_v else 1.0
    for i, feed in enumerate((1, 2, 4)):
        group_x = 0.23 + i * 0.28
        for j, variant in enumerate(("serial_batch", "pipelined_batch")):
            bx = group_x + (j - 0.5) * 0.085
            color = ORANGE if variant == "serial_batch" else TEAL
            short = "serial" if j == 0 else "pipelined"
            c.text(bx, 0.842, short, size=MINI, ha="center", color=MUTED)
            row = feeds.get(feed, {}).get(variant)
            if row is None:
                c.rect(bx - 0.040, y0, 0.080, 0.10, face="white", edge=GREY,
                       lw=1.4, dashed=True, rounded=True)
                c.text(bx, y0 + 0.05, "NOT RUN", size=MINI, ha="center", color=ORANGE_DARK)
                c.value(f"NOT RUN {short} {feed} feeds", None, source="batching.csv")
                continue
            v = float(row.extra["fps_per_feed"])
            height = (v / ymax) * (y1 - y0)
            c.rect(bx - 0.037, y0, 0.074, height, face=color, edge="white", lw=1.0)
            c.text(bx, y0 + height + 0.026, fmt(v, 1), size=VALUE,
                   ha="center", color=color, weight="bold")
        c.text(group_x, 0.19, f"{feed} feed{'s' if feed != 1 else ''}", size=VALUE,
               ha="center", weight="bold")
    c.text(0.075, 0.105, "FPS per feed is read from the extra field of batching.csv; totals are not used here.",
           size=MINI, color=MUTED)
    c.finish(footer_for(data, stem), "data-backed")


