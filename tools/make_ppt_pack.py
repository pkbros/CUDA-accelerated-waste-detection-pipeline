def build_10(data: PPTData) -> None:
    stem = "10_what_did_not_work"
    c = Canvas(stem, ["vector_add.csv", "infer.csv", "batching.csv", "device.json"])
    va = vector_add_data(data)
    ladder, _ = inference_ladder(data)
    feeds = multi_feed(data, feeds=(4,))

    def row_specs() -> list[dict[str, Any]]:
        specs: list[dict[str, Any]] = []
        if "gpu_scalar" in va and "gpu_float4" in va:
            before, after = va["gpu_scalar"].time_ms_mean, va["gpu_float4"].time_ms_mean
            specs.append({
                "title": "float4 loads vs scalar loads",
                "source": "vector_add.csv",
                "before": before, "after": after, "unit": "ms", "digits": 3,
                "before_name": "scalar", "after_name": "float4",
                "verdict": "slower" if after > before else "faster" if after < before else "equal",
                "detail": f"scalar {fmt(before, 3)} ms vs float4 {fmt(after, 3)} ms",
            })
        if 1 in ladder.get("pt_fp32", {}):
            before = ladder["pt_fp32"][1].time_ms_mean
            after = ladder.get("pt_fp16", {}).get(1)
            if after is not None:
                a = after.time_ms_mean
                specs.append({
                    "title": "FP16 inference vs FP32 inference",
                    "source": "infer.csv",
                    "before": before, "after": a, "unit": "ms", "digits": 2,
                    "before_name": "FP32", "after_name": "FP16",
                    "verdict": "slower" if a > before else "faster" if a < before else "equal",
                    "detail": f"batch 1: FP32 {fmt(before, 2)} ms vs FP16 {fmt(a, 2)} ms",
                })
        pair = feeds.get(4, {})
        if "serial_batch" in pair and "pipelined_batch" in pair:
            before = float(pair["serial_batch"].extra["fps_per_feed"])
            after = float(pair["pipelined_batch"].extra["fps_per_feed"])
            specs.append({
                "title": "Pipelined vs serial at 4 feeds",
                "source": "batching.csv",
                "before": before, "after": after, "unit": "FPS/feed", "digits": 1,
                "before_name": "serial", "after_name": "pipelined",
                "verdict": "worse" if after < before else "better" if after > before else "equal",
                "detail": f"4 feeds: serial {fmt(before, 1)} vs pipelined {fmt(after, 1)} FPS/feed",
            })
        return specs

    specs = row_specs()
    c.text(0.04, 0.95, "What did not work (measured regressions)", size=TITLE, weight="bold")
    c.text(0.04, 0.885,
           "scalar vs float4, FP32 vs FP16, serial vs pipelined - every value read from results CSVs",
           size=SUBTITLE, color=MUTED)
    if not specs:
        c.placeholder("no regression rows in vector_add.csv / infer.csv / batching.csv",
                      panel="regressions", source="vector_add.csv", y=0.5)
        c.finish(footer_for(data, stem), "placeholder: no regression data")
        return
    for i, spec in enumerate(specs):
        y = 0.70 - i * 0.22
        c.text(0.04, y + 0.085, spec["title"], size=VALUE, weight="bold")
        c.text(0.96, y + 0.085, f"after was {spec['verdict']}", size=VALUE,
               ha="right", color=ORANGE_DARK if spec["verdict"] in {"slower", "worse"} else TEAL,
               weight="bold")
        x0, x1 = 0.05, 0.82
        maxv = max(spec["before"], spec["after"]) * 1.18
        scale = (x1 - x0) / maxv
        for j, (name, v, color) in enumerate((
            (spec["before_name"], spec["before"], ORANGE),
            (spec["after_name"], spec["after"], TEAL),
        )):
            by = y + 0.005 - j * 0.048
            width = v * scale
            c.rect(x0, by, width, 0.034, face=color, edge="white", lw=1.0)
            c.text(x0 + width + 0.012, by + 0.017,
                   f"{name} {fmt(v, spec['digits'])} {spec['unit']}",
                   size=MINI, color=color, weight="bold")
            c.value(f"{spec['title']} {name}", f"{v:.6f}", unit=spec["unit"],
                    source=spec["source"], note=spec["detail"])
    c.finish(footer_for(data, stem), "data-backed")


