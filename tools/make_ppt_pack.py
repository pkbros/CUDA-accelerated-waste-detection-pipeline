def build_03(data: PPTData) -> None:
    stem = "03_latency_breakdown"
    c = Canvas(stem, ["demo_frame_timings.csv", "device.json"])
    stats = per_frame_stats(data.frames)
    stage_names = ("decode", "preprocess", "inference", "postprocess")
    base_means = [
        float(sum(getattr(f, k) for f in data.frames) / stats.n_frames)
        for k in ("baseline_decode_ms", "baseline_preprocess_ms", "baseline_infer_ms", "baseline_post_ms")
    ]
    opt_means = [
        float(sum(getattr(f, k) for f in data.frames) / stats.n_frames)
        for k in ("opt_decode_ms", "opt_preprocess_ms", "opt_infer_ms", "opt_post_ms")
    ]
    base_total, opt_total = sum(base_means), sum(opt_means)
    c.text(0.045, 0.95, "Where the milliseconds go", size=TITLE, weight="bold")
    c.text(
        0.045, 0.885,
        f"mean per frame over {stats.n_frames} frames: baseline {fmt(base_total)} ms "
        f"vs optimized {fmt(opt_total)} ms ({fmt(opt_total / base_total * 100, 1)}% of baseline)",
        size=SUBTITLE, color=MUTED,
    )
    c.value("baseline total mean", f"{base_total:.6f}", unit="ms", source="demo_frame_timings.csv")
    c.value("optimized total mean", f"{opt_total:.6f}", unit="ms", source="demo_frame_timings.csv")
    c.value("optimized percent of baseline", f"{opt_total / base_total * 100:.6f}", unit="%",
            source="demo_frame_timings.csv", note="computed from the two measured totals")

    x0, x1 = 0.075, 0.815
    width = x1 - x0
    scale = width / max(base_total, opt_total)
    rows = (
        ("baseline", 0.60, base_means, BASE_STAGES, base_total, ORANGE),
        ("optimized", 0.34, opt_means, OPT_STAGES, opt_total, TEAL),
    )
    for label, y, values, colors, total, accent in rows:
        cursor = x0
        for i, (name, value, color) in enumerate(zip(stage_names, values, colors)):
            if value <= 0:
                c.value(f"{label} {name}", f"{value:.6f}", unit="ms", panel=label,
                        source="demo_frame_timings.csv", note="zero width: not drawn")
                continue
            seg = value * scale
            c.rect(cursor, y, seg, 0.115, face=color, edge="white", lw=1.0)
            center = cursor + seg / 2.0
            if label == "baseline":
                level = y + 0.16 + (0.03 if i % 2 == 0 else 0.065)
                c.line(center, y + 0.115, center, level - 0.014, color=MUTED, lw=1.2)
            else:
                level = y - 0.06 - (0.04 if i % 2 == 0 else 0.08)
                c.line(center, y, center, level + 0.014, color=MUTED, lw=1.2)
            c.text(center, level, f"{name} {fmt(value)} ms", size=MINI,
                   ha="center", color=INK)
            c.value(f"{label} {name}", f"{value:.6f}", unit="ms", panel=label,
                    source="demo_frame_timings.csv")
            cursor += seg
        c.text(x1 + 0.012, y + 0.057, f"{fmt(total)} ms total", size=VALUE,
               color=accent, weight="bold")
    c.text(0.045, 0.17, "Each segment is a direct label on its own measured bar; no legend is needed.",
           size=MINI, color=MUTED)
    c.finish(footer_for(data, stem), "data-backed")


