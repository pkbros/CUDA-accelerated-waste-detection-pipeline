def build_05(data: PPTData) -> None:
    stem = "05_inference_ladder"
    c = Canvas(stem, ["infer.csv", "device.json"])
    ladder, batches_present = inference_ladder(data)
    all_batches = (1, 4, 8)
    backends = list(ladder.keys())
    c.text(0.04, 0.95, "Inference ladder: measured backends and batches", size=TITLE, weight="bold")
    only1 = batches_present == [1]
    suffix = " (batch 1 only)" if only1 else ""
    c.text(
        0.04, 0.885,
        f"ms per image{suffix}; batches present in infer.csv: "
        f"{', '.join(str(b) for b in batches_present)}; absent combinations read NOT RUN",
        size=SUBTITLE, color=MUTED,
    )
    c.value("batches present", ",".join(str(b) for b in batches_present), source="infer.csv")
    c.value("batch 1 only", int(only1), source="infer.csv")

    real = [r.time_ms_mean for by_batch in ladder.values() for r in by_batch.values()]
    ymax = max(real) * 1.28 if real else 1.0
    y0, y1 = 0.22, 0.74
    c.line(0.075, y0, 0.965, y0, color=INK, lw=2.0)
    c.text(0.04, y0, "0", size=MINI, ha="right")
    c.text(0.04, y1, fmt(ymax, 1), size=MINI, ha="right")
    c.text(0.09, (y0 + y1) / 2, "ms/img", size=MINI, ha="right", color=MUTED)

    for gi, backend in enumerate(backends):
        group_x = 0.18 + gi * 0.28
        for bi, batch in enumerate(all_batches):
            bx = group_x + (bi - 1) * 0.072
            c.text(bx, 0.842, f"batch {batch}", size=MINI, ha="center", color=MUTED)
            row = ladder[backend].get(batch)
            if row is None:
                c.rect(bx - 0.035, y0, 0.070, 0.10, face="white", edge=GREY, lw=1.4,
                       dashed=True, rounded=True)
                c.text(bx, y0 + 0.05, "NOT RUN", size=MINI, ha="center", color=ORANGE_DARK)
                c.value(f"NOT RUN {backend} batch {batch}", None, source="infer.csv",
                        note=f"no {backend} batch-{batch} row in infer.csv")
                continue
            height = (row.time_ms_mean / ymax) * (y1 - y0)
            color = ORANGE if "fp16" in backend else TEAL
            c.rect(bx - 0.029, y0, 0.058, height, face=color, edge="white", lw=1.0)
            c.text(bx, y0 + height + 0.028, fmt(row.time_ms_mean, 2), size=VALUE,
                   ha="center", color=color, weight="bold")
            c.value(f"{backend} batch {batch}", f"{row.time_ms_mean:.6f}", unit="ms",
                    source="infer.csv", note=f"std={row.time_ms_std:.6f} ms")
        c.text(group_x, 0.135, backend, size=VALUE, ha="center", weight="bold")
    c.text(0.075, 0.075, "FPS values in infer.csv are per-forward and are not mixed into these ms bars.",
           size=MINI, color=MUTED)
    status = "data-backed" if set(batches_present) == set(all_batches) else "partial: batch 4/8 NOT RUN"
    c.finish(footer_for(data, stem), status)


